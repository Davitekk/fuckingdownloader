"""Cookie helpers: accept Netscape cookies.txt or JSON exports (Cookie-Editor,
EditThisCookie...) and merge every slot into one Netscape file per job."""
import json
from pathlib import Path

HEADER = "# Netscape HTTP Cookie File\n# Generated by FuckinDownloader\n\n"


def _json_to_netscape(raw: str) -> list[str]:
    data = json.loads(raw)
    if isinstance(data, dict):
        data = data.get("cookies", [data])
    lines = []
    for c in data:
        domain = c.get("domain") or c.get("host") or ""
        if not domain or "name" not in c:
            continue
        include_sub = "TRUE" if domain.startswith(".") or not c.get("hostOnly", False) else "FALSE"
        if include_sub == "TRUE" and not domain.startswith("."):
            domain = "." + domain
        path = c.get("path", "/")
        secure = "TRUE" if c.get("secure") else "FALSE"
        expiry = c.get("expirationDate") or c.get("expires") or c.get("expiry") or 0
        try:
            expiry = int(float(expiry))
        except (TypeError, ValueError):
            expiry = 0
        if expiry < 0:
            expiry = 0
        lines.append("\t".join([domain, include_sub, path, secure, str(expiry), c["name"], str(c.get("value", ""))]))
    return lines


def normalize(raw: str) -> list[str]:
    """Return valid Netscape cookie lines from whatever the user pasted."""
    raw = (raw or "").strip()
    if not raw:
        return []
    if raw[0] in "[{":
        try:
            return _json_to_netscape(raw)
        except Exception:
            pass
    out = []
    for line in raw.splitlines():
        line = line.rstrip("\r\n")
        if line.startswith("#HttpOnly_"):
            pass  # valid, curl-style httponly marker
        elif not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) == 7:
            out.append(line)
        elif len(line.split()) == 7:  # tabs got mangled into spaces by copy/paste
            out.append("\t".join(line.split()))
    return out


def count(raw: str) -> int:
    return len(normalize(raw))


def write_merged(slots: dict, dest: Path) -> Path | None:
    lines = []
    for raw in slots.values():
        lines.extend(normalize(raw))
    if not lines:
        return None
    dest.write_text(HEADER + "\n".join(lines) + "\n", "utf-8")
    return dest
